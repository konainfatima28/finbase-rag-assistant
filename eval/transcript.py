"""`python -m eval.transcript eval/results/demo.json`: render real eval answers into docs/DEMO_TRANSCRIPT.md."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from app.settings import ROOT_DIR


def render(report: dict[str, Any]) -> str:
    """Markdown transcript of every answered item (verbatim system output)."""
    lines = [
        "# Demo transcript (seed questions end-to-end)",
        "",
        f"Generated by `python -m eval.transcript` from run `{report['run_id']}` ({report['created_at']}), "
        f"chat model `{report['config'].get('chat_model')}`, embeddings `{report['config'].get('embed_model')}`. "
        "Answers and sources are verbatim system output.",
        "",
    ]
    for row in report["items"]["answers"]:
        verification = row.get("verification") or {}
        lines += [
            f"## {row['id']} · {row['category']}",
            f"**Q:** {row['question']}",
            "",
            "```",
            row["formatted"],
            "```",
            f"Confidence: {row['confidence'].get('label')} ({row['confidence'].get('score')}) · "
            f"abstained: {row['abstained']} · warnings: {', '.join(verification.get('warnings') or []) or 'none'} · "
            f"latency {row['usage']['latency_ms'].get('total')} ms · cost ${row['usage']['cost_usd']}",
            "",
        ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    source = Path(args[0]) if args else ROOT_DIR / "eval" / "results" / "demo.json"
    report = json.loads(source.read_text(encoding="utf-8"))
    out = ROOT_DIR / "docs" / "DEMO_TRANSCRIPT.md"
    out.write_text(render(report), encoding="utf-8")
    sys.stdout.write(f"wrote {out} ({len(report['items']['answers'])} items)\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
